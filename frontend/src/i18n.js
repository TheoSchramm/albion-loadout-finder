// "A-Z" is a universal alphabetical-sort marker; kept identical across languages rather
// than forced into a non-Latin equivalent no one actually uses for this purpose.
for (const language of Object.keys(STRINGS)) {
  STRINGS[language].sortAlpha = 'A–Z';
}

/**
 * Look up a UI string for a language, filling in `{name}` placeholders from `params`.
 * Falls back to English, then to the key itself, so a missing translation degrades to
 * readable English rather than "undefined".
 */
export function t(key, language = DEFAULT_LANGUAGE, params = {}) {
  const table = STRINGS[String(language).toLowerCase()] || STRINGS[DEFAULT_LANGUAGE];
  const template = table[key] ?? STRINGS[DEFAULT_LANGUAGE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (params[name] !== undefined ? params[name] : match));
}
